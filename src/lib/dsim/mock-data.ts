const now = new Date();
const iso = (d: Date) => d.toISOString();
const daysFrom = (n: number, h = 10, m = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() + n);
  d.setHours(h, m, 0, 0);
  return d;
};
const dateOnly = (n: number) => iso(daysFrom(n, 9)).slice(0, 10);

